#!/usr/bin/env node
/**
 * Generates `cid-core/src/model/catalog_bundled.rs` from the models.dev
 * registry — the same open catalog opencode uses.
 *
 * Why generate instead of hand-maintaining a list: the hand-written arrays this
 * replaces went stale silently. They still offered `gemini-1.5-pro` (retired —
 * every call 404s), had no `gpt-5.x` at all, and priced `claude-sonnet-5` at
 * $3/$15 when it is $2/$10, which quietly skewed every spend estimate on what
 * is now the default model. A list a human has to remember to update is a list
 * that will be wrong again in three months.
 *
 * This file is the *fallback* baked into the binary. At runtime
 * `model::catalog` prefers a live fetch of the same registry and only falls
 * back to this snapshot when the network is unavailable — so being a little
 * stale here is survivable rather than fatal.
 *
 *   npm run models:generate   # rewrite the snapshot from the live registry
 *   npm run models:check      # CI: fail if the snapshot is not what we'd emit
 *
 * Selection: a model is included only if the registry says it supports tool
 * calling and emits text — CID is an agent platform, so a model that cannot
 * call a tool is useless here, and image/TTS/video/embedding models are noise
 * in a model picker. Date-suffixed aliases (`...-20251001`) are dropped in
 * favour of the rolling id.
 */
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const REGISTRY_URL = process.env.MODELS_REGISTRY_URL ?? "https://models.dev/api.json";
const PROVIDERS = [
  { key: "anthropic", rustConst: "ANTHROPIC_MODELS" },
  { key: "openai", rustConst: "OPENAI_MODELS" },
  { key: "google", rustConst: "GOOGLE_MODELS" },
];
// 10 rather than a smaller number for a concrete reason: at 8, the
// newest-first cut dropped Anthropic's only budget model (claude-haiku-4-5)
// and every Google Pro model, leaving a picker of near-identical flagships
// with no cheap option and no most-capable option. 10 restores both without
// resorting to name-matching heuristics about which model is "the good one".
const PER_PROVIDER_LIMIT = 10;

const outFile = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../cid-core/src/model/catalog_bundled.rs",
);

function isDatedAlias(id) {
  const tail = id.split("-").pop();
  return /^\d{8}$/.test(tail);
}

function selectModels(providerBlock) {
  const models = Object.entries(providerBlock?.models ?? {})
    .filter(([id, m]) => {
      if (!m.tool_call) return false;
      const out = m.modalities?.output ?? [];
      if (out.length !== 1 || out[0] !== "text") return false;
      if (m.cost?.input == null || m.cost?.output == null) return false;
      if (!m.limit?.context) return false;
      if (isDatedAlias(id)) return false;
      return true;
    })
    .map(([id, m]) => ({
      id,
      name: m.name ?? id,
      context: m.limit.context,
      input: m.cost.input,
      output: m.cost.output,
      release: m.release_date ?? "",
    }));
  // Newest first: the picker should lead with current models, and the first
  // entry is what a provider falls back to when no model is configured.
  models.sort((a, b) => (a.release < b.release ? 1 : a.release > b.release ? -1 : a.id < b.id ? -1 : 1));
  return models.slice(0, PER_PROVIDER_LIMIT);
}

function rustLiteral(f) {
  // Rust needs a decimal point on f64 literals; 5 -> 5.0, 0.2 stays 0.2.
  return Number.isInteger(f) ? `${f}.0` : `${f}`;
}

function emit(selections, fetchedAt) {
  const lines = [
    "// @generated by scripts/generate-model-catalog.mjs — DO NOT EDIT BY HAND.",
    "// Run `npm run models:generate` to refresh; `npm run models:check` verifies it in CI.",
    "//",
    "// Snapshot of the models.dev registry, used as the offline fallback for",
    "// `model::catalog`'s live fetch. See the generator for why this is generated",
    "// rather than hand-maintained.",
    `// Registry snapshot taken: ${fetchedAt}`,
    "",
    "use super::catalog::CatalogModel;",
    "",
  ];
  for (const { key, rustConst } of PROVIDERS) {
    const models = selections[key];
    lines.push(`/// models.dev provider \`${key}\` — ${models.length} tool-calling text models.`);
    lines.push(`pub const ${rustConst}: &[CatalogModel] = &[`);
    for (const m of models) {
      lines.push("    CatalogModel {");
      lines.push(`        id: ${JSON.stringify(m.id)},`);
      lines.push(`        name: ${JSON.stringify(m.name)},`);
      lines.push(`        context: ${m.context},`);
      lines.push(`        input_per_million: ${rustLiteral(m.input)},`);
      lines.push(`        output_per_million: ${rustLiteral(m.output)},`);
      lines.push("    },");
    }
    lines.push("];");
    lines.push("");
  }
  return lines.join("\n");
}

const res = await fetch(REGISTRY_URL);
if (!res.ok) {
  console.error(`Failed to fetch ${REGISTRY_URL}: HTTP ${res.status}`);
  process.exit(1);
}
const registry = await res.json();

const selections = {};
for (const { key } of PROVIDERS) {
  const picked = selectModels(registry[key]);
  if (picked.length === 0) {
    console.error(`Refusing to emit: registry returned no usable models for '${key}'.`);
    process.exit(1);
  }
  selections[key] = picked;
}

// The date is intentionally not the current timestamp: a re-run that changes
// nothing but the header would fail `models:check` for no real reason. Use the
// newest release date actually present in the selection.
const fetchedAt = Object.values(selections)
  .flat()
  .reduce((max, m) => (m.release > max ? m.release : max), "");

const generated = emit(selections, fetchedAt);

if (process.argv.includes("--check")) {
  const existing = readFileSync(outFile, "utf8");
  if (existing.replace(/\r\n/g, "\n") !== generated.replace(/\r\n/g, "\n")) {
    console.error(
      "cid-core/src/model/catalog_bundled.rs is out of date with the live registry.\n" +
        "Run `npm run models:generate` and commit the result.",
    );
    process.exit(1);
  }
  console.log("model catalog snapshot is up to date");
  process.exit(0);
}

writeFileSync(outFile, generated);
for (const { key } of PROVIDERS) {
  console.log(`${key}: ${selections[key].length} models — ${selections[key].map((m) => m.id).join(", ")}`);
}
console.log(`\nwrote ${outFile}`);
